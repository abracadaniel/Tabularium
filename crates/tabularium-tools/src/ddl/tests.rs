#[test]
fn alter_mysql_and_mssql() {
    let old = users(None);
    let mut new = old.clone();
    new.columns[2] = ColumnInfo { default: Some("'x'".into()), ..col("name", "varchar(50)", true) };
    new.foreign_keys.push(ForeignKeyInfo {
        name: Some("fk_self".into()),
        columns: vec!["id".into()],
        ref_table: "users".into(),
        ref_columns: vec!["id".into()],
        ..Default::default()
    });
    new.primary_key = Some(KeyInfo { name: Some("pk2".into()), columns: vec!["id".into(), "email".into()] });
    let stmts = alter_table_ddl(&old, &new, Dialect::MySql);
    assert_eq!(
        stmts,
        vec![
            "ALTER TABLE users DROP PRIMARY KEY",
            "ALTER TABLE users MODIFY COLUMN name varchar(50) DEFAULT 'x'",
            "ALTER TABLE users ADD PRIMARY KEY (id, email)",
            "ALTER TABLE users ADD CONSTRAINT fk_self FOREIGN KEY (id) REFERENCES users (id)",
        ]
    );
    let old = users(Some("dbo"));
    let mut new = old.clone();
    new.columns[2] = ColumnInfo { default: Some("'x'".into()), ..col("name", "nvarchar(50)", false) };
    new.columns.remove(3);
    let stmts = alter_table_ddl(&old, &new, Dialect::MsSql);
    assert_eq!(stmts.len(), 5, "{stmts:#?}");
    assert!(stmts[0].starts_with("DECLARE @df sysname;") && stmts[0].contains("c.name = N'created_at'"));
    assert_eq!(stmts[1], "ALTER TABLE dbo.users DROP COLUMN created_at");
    assert_eq!(stmts[2], "ALTER TABLE dbo.users ALTER COLUMN name nvarchar(50) NOT NULL");
    assert!(stmts[3].contains("OBJECT_ID(N'dbo.users')") && stmts[3].contains("N'name'"));
    assert_eq!(stmts[4], "ALTER TABLE dbo.users ADD DEFAULT 'x' FOR name");
}

#[test]
fn alter_mysql_column_move() {
    let mut old = TableInfo::new(ObjectRef::table(None, "t"));
    old.columns = vec![
        ColumnInfo { ordinal: 1, ..col("a", "int", false) },
        ColumnInfo { ordinal: 2, ..col("b", "int", false) },
    ];
    let mut new = old.clone();
    new.columns.swap(0, 1);
    new.columns[0].ordinal = 1;
    new.columns[1].ordinal = 2;
    let opts = DiffOptions { ignore_column_order: false, ..Default::default() };
    let changes = table_changes(&old, &new, &opts);
    let stmts = table_change_statements(&new.object, &changes, Dialect::MySql, Some(&old), Some(&new));
    assert_eq!(
        stmts,
        vec!["ALTER TABLE t MODIFY COLUMN b int NOT NULL FIRST", "ALTER TABLE t MODIFY COLUMN a int NOT NULL AFTER b"]
    );
    // default options ignore column order
    assert!(alter_table_ddl(&old, &new, Dialect::MySql).is_empty());
}

