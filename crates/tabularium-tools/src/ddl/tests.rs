#[test]
fn alter_sqlite_native_and_rebuild() {
    let old = users(Some("main"));
    let mut new = old.clone();
    new.columns.push(col("nick", "text", true));
    new.indexes.push(IndexInfo { name: "idx_nick".into(), columns: vec!["nick".into()], ..Default::default() });
    assert_eq!(
        alter_table_ddl(&old, &new, Dialect::Sqlite),
        vec!["ALTER TABLE users ADD COLUMN nick text", "CREATE INDEX idx_nick ON users (nick)"]
    );
    let mut new2 = old.clone();
    new2.columns.retain(|c| c.name != "created_at");
    new2.indexes.retain(|i| i.name != "idx_users_created");
    let stmts = alter_table_ddl(&old, &new2, Dialect::Sqlite);
    assert_eq!(stmts, vec!["DROP INDEX idx_users_created", "ALTER TABLE users DROP COLUMN created_at"]);

    // type change -> rebuild
    let mut new3 = old.clone();
    new3.columns[2].data_type = "varchar(20)".into();
    let stmts = alter_table_ddl(&old, &new3, Dialect::Sqlite);
    assert_eq!(stmts[0], "PRAGMA foreign_keys = OFF");
    assert!(stmts[1].starts_with("CREATE TABLE _new_users (\n    id INTEGER PRIMARY KEY AUTOINCREMENT,"));
    assert!(stmts[1].contains("name varchar(20) DEFAULT 'anon'"));
    assert_eq!(
        stmts[2],
        "INSERT INTO _new_users (id, email, name, created_at) SELECT id, email, name, created_at FROM users"
    );
    assert_eq!(stmts[3], "DROP TABLE users");
    assert_eq!(stmts[4], "ALTER TABLE _new_users RENAME TO users");
    assert_eq!(stmts[5], "CREATE INDEX idx_users_created ON users (created_at)");
    assert_eq!(stmts[6], "PRAGMA foreign_key_check");
    assert_eq!(stmts[7], "PRAGMA foreign_keys = ON");
    // without table definitions only a note can be produced
    let changes = table_changes(&old, &new3, &DiffOptions::default());
    let stmts = table_change_statements(&old.object, &changes, Dialect::Sqlite, None, None);
    assert!(stmts[0].starts_with("-- SQLite cannot"));
}

