use super::*;
use tabularium_core::{RoutineInfo, TriggerInfo};

pub(crate) fn col(name: &str, ty: &str, nullable: bool) -> ColumnInfo {
    ColumnInfo { name: name.into(), data_type: ty.into(), nullable, ..Default::default() }
}

pub(crate) fn users(schema: Option<&str>) -> TableInfo {
    let mut t = TableInfo::new(ObjectRef::table(schema, "users"));
    t.columns = vec![
        ColumnInfo { auto_increment: true, ..col("id", "integer", false) },
        ColumnInfo { comment: Some("Login email".into()), ..col("email", "varchar(255)", false) },
        ColumnInfo { default: Some("'anon'".into()), ..col("name", "text", true) },
        ColumnInfo { default: Some("CURRENT_TIMESTAMP".into()), ..col("created_at", "timestamp", false) },
    ];
    t.primary_key = Some(KeyInfo { name: Some("users_pkey".into()), columns: vec!["id".into()] });
    t.unique_keys = vec![KeyInfo { name: Some("users_email_key".into()), columns: vec!["email".into()] }];
    t.checks = vec![CheckInfo { name: Some("users_name_check".into()), expression: "length(name) > 0".into() }];
    t.indexes = vec![
        IndexInfo { name: "users_pkey".into(), columns: vec!["id".into()], unique: true, primary: true, ..Default::default() },
        IndexInfo { name: "users_email_key".into(), columns: vec!["email".into()], unique: true, ..Default::default() },
        IndexInfo { name: "idx_users_created".into(), columns: vec!["created_at".into()], ..Default::default() },
    ];
    t.comment = Some("App users".into());
    t
}

pub(crate) fn orders(schema: Option<&str>) -> TableInfo {
    let mut t = TableInfo::new(ObjectRef::table(schema, "orders"));
    t.columns = vec![
        col("id", "bigint", false),
        col("user_id", "integer", false),
        col("total", "numeric(10,2)", true),
    ];
    t.primary_key = Some(KeyInfo { name: Some("orders_pkey".into()), columns: vec!["id".into()] });
    t.foreign_keys = vec![ForeignKeyInfo {
        name: Some("orders_user_id_fkey".into()),
        columns: vec!["user_id".into()],
        ref_schema: schema.map(str::to_string),
        ref_table: "users".into(),
        ref_columns: vec!["id".into()],
        on_delete: FkAction::Cascade,
        ..Default::default()
    }];
    t
}

