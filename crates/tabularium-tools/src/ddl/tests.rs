#[test]
fn convert_table_between_dialects() {
    let mut t = users(Some("public"));
    t.columns[0] = ColumnInfo {
        default: Some("nextval('users_id_seq'::regclass)".into()),
        ..col("id", "integer", false)
    };
    t.columns[2].default = Some("'anon'::text".into());
    let m = convert_table(&t, Dialect::Postgres, Dialect::MySql);
    assert!(m.columns[0].auto_increment && m.columns[0].default.is_none());
    assert_eq!(m.columns[0].data_type, "int");
    assert_eq!(m.columns[2].data_type, "longtext");
    assert_eq!(m.columns[2].default.as_deref(), Some("'anon'"));
    let ddl = create_table_ddl(&m, Dialect::MySql);
    assert!(ddl.contains("id int NOT NULL AUTO_INCREMENT"), "{ddl}");
}
