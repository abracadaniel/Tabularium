fn alter_no_changes_for_equivalent_spellings() {
    let mut old = TableInfo::new(ObjectRef::table(None, "t"));
    old.columns = vec![
        ColumnInfo { default: Some("'a'::character varying".into()), ..col("s", "character varying(10)", true) },
        col("n", "int4", false),
        ColumnInfo { default: Some("(0)".into()), ..col("x", "NUMERIC(10, 2)", true) },
    ];
    let mut new = old.clone();
    new.columns[0] = ColumnInfo { default: Some("'a'".into()), ..col("s", "varchar(10)", true) };
    new.columns[1] = col("n", "integer", false);
    new.columns[2] = ColumnInfo { default: Some("0".into()), ..col("x", "decimal(10,2)", true) };
    assert!(alter_table_ddl(&old, &new, Dialect::Postgres).is_empty());
}

