    assert_eq!(
        back,
        vec![
            "ALTER TABLE t DROP CONSTRAINT t_code_key",
            "ALTER TABLE t DROP CONSTRAINT t_check",
            "ALTER TABLE t DROP CONSTRAINT t_pkey",
            "ALTER TABLE t ALTER COLUMN id DROP NOT NULL",
            "ALTER TABLE t ALTER COLUMN id DROP IDENTITY IF EXISTS",
        ]
    );
