#[test]
fn identity_variants() {
    let serial = ColumnInfo {
        auto_increment: true,
        default: Some("nextval('t_id_seq'::regclass)".into()),
        ..col("id", "serial", false)
    };
    assert_eq!(column_definition(&serial, Dialect::Postgres, false), "id serial NOT NULL");
    let nextval = ColumnInfo { data_type: "integer".into(), ..serial.clone() };
    assert_eq!(
        column_definition(&nextval, Dialect::Postgres, false),
        "id integer NOT NULL DEFAULT nextval('t_id_seq'::regclass)"
    );
    let gen = ColumnInfo { generated: Some("price * qty".into()), ..col("total", "numeric", true) };
    assert_eq!(column_definition(&gen, Dialect::Postgres, false), "total numeric GENERATED ALWAYS AS (price * qty) STORED");
    assert_eq!(column_definition(&gen, Dialect::MsSql, false), "total AS (price * qty) PERSISTED");
    let coll = ColumnInfo { collation: Some("C".into()), ..col("code", "text", false) };
    assert_eq!(column_definition(&coll, Dialect::Postgres, false), "code text COLLATE \"C\" NOT NULL");
    // composite PK in SQLite with auto-increment: no inline AUTOINCREMENT
    let mut t = TableInfo::new(ObjectRef::table(None, "t"));
    t.columns = vec![ColumnInfo { auto_increment: true, ..col("a", "integer", false) }, col("b", "integer", false)];
    t.primary_key = Some(KeyInfo { name: None, columns: vec!["a".into(), "b".into()] });
    assert_eq!(
        create_table_ddl(&t, Dialect::Sqlite),
        "CREATE TABLE t (\n    a integer NOT NULL,\n    b integer NOT NULL,\n    PRIMARY KEY (a, b)\n);\n"
    );
}

#[test]
fn postgres_index_definition_verbatim() {
    let mut t = users(Some("public"));
    t.indexes.push(IndexInfo {
        name: "idx_lower_email".into(),
        columns: vec!["lower(email)".into()],
        definition: Some("CREATE INDEX idx_lower_email ON public.users USING btree (lower((email)::text))".into()),
        ..Default::default()
    });
    t.indexes.push(IndexInfo {
        name: "idx_gin".into(),
        columns: vec!["name".into()],
        method: Some("gin".into()),
        predicate: Some("(name IS NOT NULL)".into()),
        ..Default::default()
    });
    let ddl = create_table_ddl(&t, Dialect::Postgres);
    assert!(ddl.contains("CREATE INDEX idx_lower_email ON public.users USING btree (lower((email)::text));\n"));
    assert!(ddl.contains("CREATE INDEX idx_gin ON public.users USING gin (name) WHERE name IS NOT NULL;\n"));
    // MySQL ignores the native definition and the partial predicate
    let ddl = create_table_ddl(&t, Dialect::MySql);
    assert!(ddl.contains("CREATE INDEX idx_lower_email ON public.users (lower(email));\n"), "{ddl}");
    // re-targeted into another schema
    let idx = &t.indexes[3];
    assert_eq!(
        index_ddl(idx, &ObjectRef::table(Some("staging"), "users"), Dialect::Postgres),
        "CREATE INDEX idx_lower_email ON staging.users USING btree (lower((email)::text))"
    );
}

