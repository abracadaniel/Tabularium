    let mut new = old.clone();
    new.columns[0] = ColumnInfo { auto_increment: true, ..col("id", "integer", false) };
    new.primary_key = Some(KeyInfo { name: None, columns: vec!["id".into()] });
    new.unique_keys = vec![KeyInfo { name: Some("t_code_key".into()), columns: vec!["code".into()] }];
